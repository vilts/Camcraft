#!/usr/bin/env python3
"""Regenerate contour-tabs.obj, the model of the catalog case 2d/contour-tabs.

The part is a clean-room Camcraft fixture: a 90 x 50 x 6 mm plate with four
10 mm corner chamfers, centred on the XY origin, z from 0 to 6. A 2D Contour
cuts it out of a 120 x 80 x 6 mm sheet and leaves four tabs.

Method: the solid is a prism over one convex octagon. The top and the bottom
are triangle fans from the first corner, and each side is one quad. All faces
share the same sixteen corners, so the mesh has no T-junctions. The script
checks that the mesh is watertight and consistently oriented before it
writes the file.

Usage: python gen_contour_tabs_obj.py [output.obj]
"""

import sys

HALF_X = 45.0
HALF_Y = 25.0
CHAMFER = 10.0
Z_BOTTOM = 0.0
Z_TOP = 6.0

# Counter-clockwise seen from +Z.
OUTLINE = [
    (HALF_X - CHAMFER, -HALF_Y),
    (HALF_X, -HALF_Y + CHAMFER),
    (HALF_X, HALF_Y - CHAMFER),
    (HALF_X - CHAMFER, HALF_Y),
    (-HALF_X + CHAMFER, HALF_Y),
    (-HALF_X, HALF_Y - CHAMFER),
    (-HALF_X, -HALF_Y + CHAMFER),
    (-HALF_X + CHAMFER, -HALF_Y),
]


def build():
    n = len(OUTLINE)
    bottom = [(x, y, Z_BOTTOM) for x, y in OUTLINE]
    top = [(x, y, Z_TOP) for x, y in OUTLINE]
    faces = []
    for i in range(1, n - 1):
        faces.append([top[0], top[i], top[i + 1]])            # normal +Z
        faces.append([bottom[0], bottom[i + 1], bottom[i]])   # normal -Z
    for i in range(n):
        j = (i + 1) % n
        faces.append([bottom[i], bottom[j], top[j], top[i]])  # normal outward
    return faces


def check(faces):
    """Watertight and consistently oriented: every directed edge appears
    exactly once and its reverse appears exactly once."""
    seen = set()
    for face in faces:
        for p, q in zip(face, face[1:] + face[:1]):
            if p == q:
                raise SystemExit("degenerate face: %r" % (face,))
            if (p, q) in seen:
                raise SystemExit("directed edge reused: %r -> %r" % (p, q))
            seen.add((p, q))
    for (p, q) in seen:
        if (q, p) not in seen:
            raise SystemExit("open edge: %r -> %r" % (p, q))


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else "contour-tabs.obj"
    faces = build()
    check(faces)

    vid = {}
    vlines = []
    for face in faces:
        for p in face:
            if p not in vid:
                vid[p] = len(vlines) + 1
                vlines.append("v %g %g %g" % p)
    flines = ["f " + " ".join(str(vid[p]) for p in face) for face in faces]

    with open(out, "w") as fh:
        fh.write(HEADER)
        fh.write("\n" + "\n".join(vlines) + "\n\n" + "\n".join(flines) + "\n")
    print("wrote %s: %d vertices, %d faces" % (out, len(vlines), len(flines)))


HEADER = """\
# Camcraft example catalog, case 2d/contour-tabs: a 90 x 50 x 6 mm plate
# with four 10 mm corner chamfers, centred on the XY origin, z 0 to 6.
# Authored for this repository (clean-room fixture); generated by
# gen_contour_tabs_obj.py as a watertight mesh."""

if __name__ == "__main__":
    main()
