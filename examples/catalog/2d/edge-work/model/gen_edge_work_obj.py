#!/usr/bin/env python3
"""Provenance: original rectangular plate fixture, built from planar quads.

Run from model/: python3 gen_edge_work_obj.py
The plate spans x +/-30, y +/-20, z 0..6 millimetres.
"""
from pathlib import Path

vertices = [
    (-30, -20, 0), (30, -20, 0), (30, 20, 0), (-30, 20, 0),
    (-30, -20, 6), (30, -20, 6), (30, 20, 6), (-30, 20, 6),
]
faces = [(4, 3, 2, 1), (5, 6, 7, 8), (1, 2, 6, 5),
         (2, 3, 7, 6), (3, 4, 8, 7), (4, 1, 5, 8)]
edges = [(a, b) for face in faces for a, b in zip(face, face[1:] + face[:1])]
assert len(set(edges)) == len(edges), "reused directed edge"
assert all((b, a) in edges for a, b in edges), "open or reversed face"
text = "# Original CamCraft edge-work plate; generated by gen_edge_work_obj.py\n"
text += "\n".join("v %g %g %g" % v for v in vertices) + "\n"
text += "\n".join("f " + " ".join(map(str, f)) for f in faces) + "\n"
Path(__file__).with_name("edge-work.obj").write_text(text)
