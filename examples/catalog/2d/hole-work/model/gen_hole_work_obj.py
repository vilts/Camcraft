#!/usr/bin/env python3
"""Provenance: original annular-cell plate mesh for CamCraft issue #2862."""
from collections import Counter
from math import cos, sin, tau
from pathlib import Path

N = 96
TOP = 20.0
# Four drill envelopes on a 60 mm bolt circle, a bore, a circular pocket,
# and the M8x1.25 minor hole. The thread has a deeper tap-drill floor.
HOLES = {(0, 30): (3.2, 0), (30, 0): (3.2, 0),
         (0, -30): (3.2, 0), (-30, 0): (3.2, 0),
         (-30, 30): (8.2, 0), (30, 30): (5.2, 0),
         (0, 0): (3.3235, 4)}


def build():
    faces = []
    for cx in (-30, 0, 30):
        for cy in (-30, 0, 30):
            radius, floor = HOLES.get((cx, cy), (0, 0))

            def point(k, z, inner=False):
                x, y = cos(tau * (k % N) / N), sin(tau * (k % N) / N)
                scale = radius if inner else 15 / max(abs(x), abs(y))
                return (round(cx + scale * x, 10), round(cy + scale * y, 10), z)

            for k in range(N):
                p, q = point(k, TOP), point(k + 1, TOP)
                b, c = point(k, 0), point(k + 1, 0)
                if radius:
                    i, j = point(k, TOP, True), point(k + 1, TOP, True)
                    u, v = point(k, floor, True), point(k + 1, floor, True)
                    faces.extend([(p, q, j, i), (v, u, i, j)])
                    if floor == 0:
                        faces.append((c, b, u, v))
                    else:
                        faces.extend([((cx, cy, floor), u, v), ((cx, cy, 0), c, b)])
                else:
                    faces.extend([((cx, cy, TOP), p, q), ((cx, cy, 0), c, b)])
                # Only the external plate boundary needs vertical walls.
                if ((p[0] == q[0] and abs(p[0]) == 45)
                        or (p[1] == q[1] and abs(p[1]) == 45)):
                    faces.append((b, c, q, p))
    return faces


def main():
    faces = build()
    edges = Counter((p, q) for face in faces for p, q in zip(face, face[1:] + face[:1]))
    for (p, q), count in edges.items():
        if p == q or count != 1 or edges[(q, p)] != 1:
            raise SystemExit(f"mesh has an open, repeated or degenerate edge: {p}, {q}")
    vertices = dict.fromkeys(p for face in faces for p in face)
    indices = {p: i for i, p in enumerate(vertices, 1)}
    out = Path(__file__).with_name("hole-work.obj")
    lines = ["# Original 90 x 90 x 20 mm hole-work plate; generated by gen_hole_work_obj.py."]
    lines.extend("v %.10g %.10g %.10g" % p for p in vertices)
    lines.extend("f " + " ".join(str(indices[p]) for p in face) for face in faces)
    out.write_text("\n".join(lines) + "\n")
    print(f"wrote {out.name}: {len(vertices)} vertices, {len(faces)} faces")


if __name__ == "__main__":
    main()
