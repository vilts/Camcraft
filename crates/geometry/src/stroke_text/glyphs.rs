//! Provenance: the glyph table of our own single-line engraving font (issue 2679). Each glyph
//! was drawn from scratch for this project on a 4 x 6 grid, with straight strokes and cut
//! corners. No font file, no vendor letter shape and no other stroke font was consulted.
//!
//! Drawing rules, which keep each stroke a clean chain (`sketch_chains`: a chain cannot branch):
//! - An end of a stroke meets a different stroke only inside one of its segments, never at a
//!   corner or an end. Where three lines would meet at a corner, one line runs through.
//! - Only a closed stroke repeats its first point as its last point.
//! - The cap height is `CAP` units, the baseline is y = 0, and x starts at 0.

/// A point in font units.
pub(super) type P = (f64, f64);

pub(super) struct Glyph {
    pub ch: char,
    /// The advance width in font units, without the gap to the next glyph.
    pub width: f64,
    pub strokes: &'static [&'static [P]],
}

/// The cap height in font units.
pub(super) const CAP: f64 = 6.0;
/// The gap between two glyphs in font units.
pub(super) const GAP: f64 = 2.0;

/// The closed eight-corner ring that O, Q and 0 share.
const RING: &[P] = &[(1., 0.), (3., 0.), (4., 1.), (4., 5.), (3., 6.), (1., 6.), (0., 5.), (0., 1.), (1., 0.)];
/// The bowl and stem that P and R share; the bowl ends inside the stem.
const P_STROKE: &[P] = &[(0., 0.), (0., 6.), (3., 6.), (4., 5.), (4., 4.), (3., 3.), (0., 3.)];

const fn g(ch: char, width: f64, strokes: &'static [&'static [P]]) -> Glyph {
    Glyph { ch, width, strokes }
}

